import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { afterEach, describe, expect, it, vi } from "vitest";
import { HelpHub, HelpTopic } from "./HelpPages";
import { GoogleOAuthSetupWarning } from "@/client/features/integrations/GoogleOAuthSetupWarning";
import { createMemoryHistory, createRouter } from "@tanstack/react-router";
import { routeTree } from "@/routeTree.gen";
import type * as AuthMode from "@/lib/auth-mode";
import { setRuntimeAuthMode } from "@/lib/auth-mode";

const mode = vi.hoisted(() => ({ everyApp: false }));
vi.mock("cloudflare:workers", () => ({
  env: {},
  waitUntil: () => {},
  DurableObject: Object,
}));
vi.mock("@/lib/auth-mode", async (importOriginal) => ({
  ...(await importOriginal<typeof AuthMode>()),
  isEveryAppClientAuthMode: () => mode.everyApp,
}));

afterEach(() => {
  vi.unstubAllGlobals();
  mode.everyApp = false;
  setRuntimeAuthMode(undefined);
});

describe("native setup help", () => {
  it("routes authentication help outside the signed-in app and renders recovery guidance", () => {
    const router = createRouter({
      routeTree,
      history: createMemoryHistory({
        initialEntries: ["/help/authentication"],
      }),
    });
    const matches = router.matchRoutes("/help/authentication");
    expect(matches.map((match) => match.routeId)).toEqual([
      "__root__",
      "/help/authentication",
    ]);
    const html = renderToStaticMarkup(
      createElement(HelpTopic, { topic: "authentication" }),
    );
    expect(html).toContain("reset your password");
    expect(html).toContain("Every App");
    expect(html).toContain("Cloudflare Access");
    expect(html).toContain("Managed OAuth");
    expect(html).toContain("redirect URIs");
  });
  it("offers working local topic destinations", () => {
    const html = renderToStaticMarkup(createElement(HelpHub));
    expect(html).toContain('href="/help/google-analytics"');
    expect(html).toContain('href="/help/dataforseo-api-key"');
    expect(
      renderToStaticMarkup(createElement(HelpTopic, { topic: "crawler" })),
    ).toContain("robots rules");
  });

  it.each([
    ["google-analytics", "/api/ga4/oauth/callback"],
    ["google-search-console", "/api/gsc/oauth/callback"],
  ])(
    "shows the current origin and correct callback for %s",
    (topic, callback) => {
      vi.stubGlobal("window", {
        location: { origin: "https://seo.example.com" },
      });
      const html = renderToStaticMarkup(createElement(HelpTopic, { topic }));
      expect(html).toContain(`https://seo.example.com${callback}`);
      expect(html).toContain("BETTER_AUTH_SECRET");
      expect(html).toContain("If <code>BETTER_AUTH_SECRET</code> is absent");
      expect(html).toContain("at least 32 characters");
      expect(html).toContain("Keep any existing secret unchanged");
      expect(html).toContain("generated by Docker");
      expect(html).toContain("do not automatically rotate it");
    },
  );

  it("links an unavailable Google integration to its native guide", () => {
    const html = renderToStaticMarkup(
      createElement(GoogleOAuthSetupWarning, {
        integrationName: "Google Analytics",
        docsUrl: "/help/google-analytics",
      }),
    );
    expect(html).toContain('href="/help/google-analytics"');
    expect(html).toContain("administrator");
  });
  it("keeps the Every App gateway callback distinct from local callbacks", () => {
    mode.everyApp = true;
    const html = renderToStaticMarkup(
      createElement(HelpTopic, { topic: "google-analytics" }),
    );
    expect(html).toContain("/connect/google-workspace/callback");
    expect(html).not.toContain("/api/ga4/oauth/callback");
  });
  it("directs Every App agents to the gateway flow without an app endpoint or key", () => {
    setRuntimeAuthMode("everyapp");
    vi.stubGlobal("window", {
      location: { origin: "https://seo.example.com" },
    });
    const html = renderToStaticMarkup(
      createElement(HelpTopic, { topic: "agent" }),
    );
    expect(html).toContain('href="/ai"');
    expect(html).toContain("verified gateway");
    expect(html).not.toContain("seo.example.com/mcp");
    expect(html).not.toContain("API key");
  });
  it.each(["password", "hosted", "local_noauth", "cloudflare_access"])(
    "gives %s clients the appropriate connection guidance",
    (authMode) => {
      setRuntimeAuthMode(authMode);
      vi.stubGlobal("window", {
        location: { origin: "https://seo.example.com" },
      });
      const html = renderToStaticMarkup(
        createElement(HelpTopic, { topic: "agent" }),
      );
      expect(html).toContain("https://seo.example.com/mcp");
      expect(html).toContain("localhost");
      if (authMode === "password" || authMode === "hosted") {
        expect(html).toContain("create an API key");
      } else {
        expect(html).not.toContain("create an API key");
        expect(html).toContain(
          authMode === "local_noauth"
            ? "does not require an API key"
            : "Managed OAuth",
        );
      }
    },
  );
});
